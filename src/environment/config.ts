export type V04Settings = {
  [K in keyof typeof V04_RULES]: (typeof V04_RULES)[K]['value'] extends boolean ? boolean : number;
};
export const V04_DEFAULTS = Object.fromEntries(
  Object.entries(V04_RULES).map(([k, r]) => [k, r.value]),
) as V04Settings;
export const INITIAL_KEYS = Object.keys(V04_RULES).filter(
  (k) =>
    k.startsWith('initial') ||
    ['customInitial', 'randomPosRange', 'randomSpeedRange', 'planetMassOriginal'].includes(k),
) as (keyof V04Settings)[];
export function validateV04(config: V04Settings): void {
  for (const [key, rule] of Object.entries(V04_RULES)) {
    const value = config[key as keyof V04Settings];
    if (typeof rule.value === 'boolean') {
      if (typeof value !== 'boolean') throw new Error(`Invalid ${key}`);
    } else if (
      typeof value !== 'number' ||
      !Number.isFinite(value) ||
      !('min' in rule) ||
      value < rule.min ||
      value > rule.max
    )
      throw new Error(`Invalid ${key}`);
  }
}

export function v04FromSettings(settings: V04Settings): V04Settings {
  return Object.fromEntries(
    Object.keys(V04_RULES).map((k) => [k, settings[k as keyof V04Settings]]),
  ) as V04Settings;
}
